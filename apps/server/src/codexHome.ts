import {
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import {
  BUILDER_CODEX_HOME,
  CLAUDE_PLUGIN_CACHE,
  CLAUDE_PLUGIN_SKILLS,
  CLAUDE_SKILLS,
  CLAUDE_SKILLS_DIR,
  CODEX_ISOLATED,
  CODEX_PLUGIN_CACHE,
  CODEX_PLUGINS,
  CODEX_SKILL_SOURCES,
  EXPO_MCP_ENABLED,
  EXPO_MCP_URL,
  MEMPALACE_ENABLED,
  MEMPALACE_SERVER,
  MEMPALACE_URL,
  MODEL_PROVIDER,
  MODEL_PROVIDER_API,
  MODEL_PROVIDER_KEY_ENV,
  MODEL_PROVIDER_URL,
  USER_CODEX_HOME,
} from "./config.ts";

function isSkillDir(dir: string): boolean {
  return existsSync(path.join(dir, "SKILL.md"));
}

function safeReaddir(dir: string): string[] {
  try {
    return readdirSync(dir).filter((name) => !name.startsWith("."));
  } catch {
    return [];
  }
}

/**
 * Skill folders of the named Codex plugins: <cache>/<marketplace>/<plugin>/
 * <version>/skills. Every installed version is offered; the link helper keeps
 * the first it sees and leaves an existing link alone.
 */
function codexPluginSkillDirs(): string[] {
  const out: string[] = [];
  for (const marketplace of safeReaddir(CODEX_PLUGIN_CACHE)) {
    for (const plugin of CODEX_PLUGINS) {
      const pluginDir = path.join(CODEX_PLUGIN_CACHE, marketplace, plugin);
      for (const version of safeReaddir(pluginDir)) {
        const skills = path.join(pluginDir, version, "skills");
        if (existsSync(skills)) out.push(skills);
      }
    }
  }
  return out;
}

/** The named skills wherever a Claude plugin cache holds them: <cache>/<marketplace>/<plugin>/<version>/skills/<name>. */
function claudePluginSkills(): { name: string; source: string }[] {
  const out: { name: string; source: string }[] = [];
  for (const marketplace of safeReaddir(CLAUDE_PLUGIN_CACHE)) {
    for (const plugin of safeReaddir(path.join(CLAUDE_PLUGIN_CACHE, marketplace))) {
      for (const version of safeReaddir(path.join(CLAUDE_PLUGIN_CACHE, marketplace, plugin))) {
        for (const name of CLAUDE_PLUGIN_SKILLS) {
          const source = path.join(CLAUDE_PLUGIN_CACHE, marketplace, plugin, version, "skills", name);
          if (isSkillDir(source)) out.push({ name, source });
        }
      }
    }
  }
  return out;
}

/**
 * Link skills into the builder home. Links, not copies, so a skill updated in
 * its source folder is what the agent reads next turn. An existing entry is
 * left alone, whatever it points at.
 */
function syncSkills(home: string): void {
  const target = path.join(home, "skills");
  mkdirSync(target, { recursive: true });
  const link = (name: string, source: string) => {
    if (!isSkillDir(source)) return;
    const dest = path.join(target, name);
    try {
      lstatSync(dest);
      return;
    } catch {
      /* not linked yet */
    }
    try {
      symlinkSync(source, dest, "dir");
    } catch {
      /* a race with another boot; the next one sees it */
    }
  };
  for (const sourceDir of CODEX_SKILL_SOURCES) {
    let entries: string[] = [];
    try {
      entries = readdirSync(sourceDir);
    } catch {
      continue;
    }
    for (const name of entries) {
      if (name.startsWith(".")) continue;
      link(name, path.join(sourceDir, name));
    }
  }
  for (const name of CLAUDE_SKILLS) link(name, path.join(CLAUDE_SKILLS_DIR, name));
  for (const skills of codexPluginSkillDirs()) {
    for (const name of safeReaddir(skills)) link(name, path.join(skills, name));
  }
  for (const { name, source } of claudePluginSkills()) link(name, source);
}

/**
 * A Codex home owned by the builder.
 *
 * Regenerated on every use so a changed BUILDER_* setting takes effect without
 * anyone editing the file. It declares no plugins and no hooks on purpose: the
 * engineering policy that gates interactive terminal sessions must not gate an
 * unattended agent whose every turn is already committed and reviewable.
 */
function configToml(): string {
  const lines = [
    "# Generated by Runner Builder. Change BUILDER_* environment variables, not this file.",
    "# No plugins and no hooks: this home exists so the agent runs ungated inside",
    "# repositories whose terminal sessions are policy-gated.",
    "",
  ];
  if (MEMPALACE_ENABLED) {
    lines.push(
      `[mcp_servers.${MEMPALACE_SERVER}]`,
      `url = ${JSON.stringify(MEMPALACE_URL)}`,
      'bearer_token_env_var = "MEMPALACE_TOKEN"',
      'enabled_tools = ["mempalace_search", "mempalace_status"]',
      'default_tools_approval_mode = "auto"',
      "",
    );
  }
  if (MODEL_PROVIDER) {
    // A local or self-hosted OpenAI-compatible server. The agent command
    // selects it with model_provider; this block tells Codex where it is.
    lines.push(
      `[model_providers.${MODEL_PROVIDER}]`,
      `name = ${JSON.stringify(MODEL_PROVIDER)}`,
      `base_url = ${JSON.stringify(MODEL_PROVIDER_URL)}`,
      `wire_api = ${JSON.stringify(MODEL_PROVIDER_API)}`,
      ...(MODEL_PROVIDER_KEY_ENV ? [`env_key = ${JSON.stringify(MODEL_PROVIDER_KEY_ENV)}`] : []),
      "",
    );
  }
  if (EXPO_MCP_ENABLED) {
    // Current Expo docs, `expo install`, EAS builds and TestFlight data for the
    // agent. Authenticated once from this home with `codex mcp login expo`.
    lines.push("[mcp_servers.expo]", `url = ${JSON.stringify(EXPO_MCP_URL)}`, 'default_tools_approval_mode = "auto"', "");
  }
  return lines.join("\n");
}

/**
 * The home the codex child should run from, created or refreshed as needed.
 * Null means the person's own Codex home (isolation switched off).
 */
export function ensureCodexHome(): string | null {
  if (!CODEX_ISOLATED) return null;
  mkdirSync(BUILDER_CODEX_HOME, { recursive: true });

  const configPath = path.join(BUILDER_CODEX_HOME, "config.toml");
  const desired = configToml();
  let current = "";
  try {
    current = readFileSync(configPath, "utf8");
  } catch {
    /* first run */
  }
  if (current !== desired) writeFileSync(configPath, desired);
  syncSkills(BUILDER_CODEX_HOME);

  // The login is shared rather than copied: a token refresh by either side is
  // seen by both, and no credential is duplicated on disk. An existing file or
  // link, even a dangling one, is left alone — it is the person's to manage.
  const auth = path.join(BUILDER_CODEX_HOME, "auth.json");
  const source = path.join(USER_CODEX_HOME, "auth.json");
  let present = true;
  try {
    lstatSync(auth);
  } catch {
    present = false;
  }
  if (!present && existsSync(source)) symlinkSync(source, auth);

  return BUILDER_CODEX_HOME;
}
